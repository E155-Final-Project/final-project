"""
Generate FPGA memory images and testbench vectors from a trained checkpoint.

Everything is produced by the integer golden model (XNOR + popcount + compare),
so it is exactly what the RTL must reproduce, bit for bit.

Memory images (--mem-dir), loaded by the FPGA build and the testbench:
  l<i>_weights.mem   WORD-bit hex, neuron-major (neuron m, words 0..k-1), pad bits = 1
  l<i>_thresh.mem    popcount threshold per neuron (hidden layers only)
  bnn_params.svh     layer sizes / widths as SystemVerilog localparams

Vector sets (--vec-dir/<set>/), one line per value, image-major:
  inputs.mem         input image bits, L0_WORDS words per image, pad bits = 0
  labels.mem         true label per image
  expected.mem       golden prediction per image (argmax, first max wins)
  vectors.svh        N_IMAGES / HAS_TRACE localparams for the testbench
  with --trace (the "smoke" set), the intermediate results of every layer:
  l<i>_popcount.mem  popcount per neuron, L<i>_N_OUT lines per image
  l<i>_act.mem       hidden layers: activation bits packed like inputs.mem,
                     i.e. exactly the next layer's input buffer

Usage:
  python gen_vectors.py --ckpt ../models/x.weights.h5 --mem-dir ../mem \
      --vec-dir ../vectors --smoke 16 --full 0 --report ../results/golden.txt
"""
import argparse
import math
import os

import numpy as np

from bnn_emnist import (WORD, build_fpga_mlp, extract_layers, golden_infer,
                        input_bits, load_emnist, pack_words, write_mem, xnor_popcount)


def golden_trace(bits, net):
    """Same arithmetic as golden_infer, but keeps every layer's popcounts and activations."""
    a = bits
    trace = []
    for w, th in net:
        p = xnor_popcount(a, w)
        if th is None:
            trace.append((p, None))
            break
        a = (p >= th).astype(np.int64)
        trace.append((p, a))
    return trace


def clog2(n):
    return max(1, math.ceil(math.log2(n)))


def write_params(path, net, ckpt):
    lines = [f"// Generated by src/gen_vectors.py from {os.path.basename(ckpt)}. Do not edit.",
             f"localparam int WORD        = {WORD};",
             f"localparam int N_LAYERS    = {len(net)};",
             f"localparam int NUM_CLASSES = {net[-1][0].shape[1]};"]
    for i, (w, th) in enumerate(net):
        N, M = w.shape
        lines += [f"localparam int L{i}_N_IN    = {N};",
                  f"localparam int L{i}_N_OUT   = {M};",
                  f"localparam int L{i}_WORDS   = {-(-N // WORD)};   // words per neuron",
                  f"localparam int L{i}_PC_BITS = {clog2(N + 1)};"]
        if th is not None:
            lines.append(f"localparam int L{i}_TH_BITS = {clog2(N + 2)};")
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")


def write_mems(mem_dir, net, ckpt):
    os.makedirs(mem_dir, exist_ok=True)
    for i, (w, th) in enumerate(net):
        words = []
        for m in range(w.shape[1]):
            words += pack_words(w[:, m], pad_value=1)
        write_mem(os.path.join(mem_dir, f"l{i}_weights.mem"), words, WORD)
        if th is not None:
            write_mem(os.path.join(mem_dir, f"l{i}_thresh.mem"), th.tolist(), clog2(w.shape[0] + 2))
    write_params(os.path.join(mem_dir, "bnn_params.svh"), net, ckpt)


def write_set(out_dir, bits, labels, net, trace):
    os.makedirs(out_dir, exist_ok=True)
    n = len(bits)
    tr = golden_trace(bits, net)
    pred = np.argmax(tr[-1][0], axis=1)
    assert np.array_equal(pred, golden_infer(bits, net)[0]), "golden_trace diverged from golden_infer"

    cls_bits = clog2(net[-1][0].shape[1])
    write_mem(os.path.join(out_dir, "inputs.mem"),
              [wd for b in bits for wd in pack_words(b, pad_value=0)], WORD)
    write_mem(os.path.join(out_dir, "labels.mem"), labels.tolist(), cls_bits)
    write_mem(os.path.join(out_dir, "expected.mem"), pred.tolist(), cls_bits)
    if trace:
        for i, ((w, _), (p, a)) in enumerate(zip(net, tr)):
            write_mem(os.path.join(out_dir, f"l{i}_popcount.mem"), p.reshape(-1).tolist(),
                      clog2(w.shape[0] + 1))
            if a is not None:
                write_mem(os.path.join(out_dir, f"l{i}_act.mem"),
                          [wd for row in a for wd in pack_words(row, pad_value=0)], WORD)
    with open(os.path.join(out_dir, "vectors.svh"), "w") as f:
        f.write(f"// Generated by src/gen_vectors.py. Do not edit.\n"
                f"localparam int N_IMAGES  = {n};\n"
                f"localparam bit HAS_TRACE = {int(trace)};\n")
    print(f"Wrote {n} vectors{' + per-layer trace' if trace else ''} to {out_dir}/")


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--ckpt", required=True)
    p.add_argument("--split", default="balanced")
    p.add_argument("--hidden", default="512,512,512")
    p.add_argument("--mem-dir", required=True)
    p.add_argument("--vec-dir", required=True)
    p.add_argument("--smoke", type=int, default=16, help="images in the traced smoke set")
    p.add_argument("--full", type=int, default=0, help="images in the full set (0 = whole test split)")
    p.add_argument("--report", default=None, help="write golden-model accuracy here")
    a = p.parse_args()

    _, _, test, num_classes = load_emnist(a.split, 1024)
    model = build_fpga_mlp(num_classes, tuple(int(h) for h in a.hidden.split(",")))
    model.load_weights(a.ckpt)
    net = extract_layers(model)

    xs, ys = zip(*[(x.numpy(), y.numpy()) for x, y in test.unbatch()])
    x_test, y_test = np.stack(xs), np.array(ys)
    bits = input_bits(x_test)

    write_mems(a.mem_dir, net, a.ckpt)

    pred_hw, _ = golden_infer(bits, net)
    pred_keras = np.argmax(model.predict(x_test, batch_size=1024, verbose=0), axis=1)
    report = (f"checkpoint: {a.ckpt}\nsplit: {a.split}  hidden: {a.hidden}  test images: {len(bits)}\n"
              f"golden accuracy: {np.mean(pred_hw == y_test):.4%}\n"
              f"golden vs keras agreement: {np.mean(pred_hw == pred_keras):.4%} "
              f"({np.sum(pred_hw != pred_keras)} mismatches)\n")
    print(report, end="")
    if a.report:
        os.makedirs(os.path.dirname(a.report) or ".", exist_ok=True)
        with open(a.report, "w") as f:
            f.write(report)

    n_full = a.full or len(bits)
    write_set(os.path.join(a.vec_dir, "smoke"), bits[:a.smoke], y_test[:a.smoke], net, trace=True)
    write_set(os.path.join(a.vec_dir, "full"), bits[:n_full], y_test[:n_full], net, trace=False)


if __name__ == "__main__":
    main()
