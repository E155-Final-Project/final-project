#!/usr/bin/env python3
"""
Convert the BNN weight and threshold .mem files into C arrays for MCU flash.

Reads   <mem-dir>/bnn_params.svh, l<i>_weights.mem, l<i>_thresh.mem
Writes  src/weights.h  (sizes, layer offsets, extern declarations, checksum)
        src/weights.c  (const arrays; the linker places them in flash)

Layout matches BNN/README.md and the SPI protocol:
  bnn_weights[]  64-bit words, layers concatenated in order 0..N-1, each layer
                 neuron-major; bit j of word k = input k*64 + j; pad bits = 1
  bnn_thresh[]   16-bit popcount thresholds, hidden layers concatenated 0..N-2

Usage (from project_mcu/):
  python3 tools/mem2c.py                       # reads ../BNN/mem
  python3 tools/mem2c.py --mem-dir path/to/mem # a different weight set
Only the Python standard library is needed. Re-run whenever the weights change.
"""
import argparse
import hashlib
import os
import re
import sys
import zlib

WORD = 64


def fail(msg):
    sys.exit(f"mem2c: error: {msg}")


def read_params(path):
    """localparam int NAME = value;  ->  {NAME: value}"""
    if not os.path.isfile(path):
        fail(f"cannot find {path}")
    params = {}
    pat = re.compile(r"localparam\s+int\s+(\w+)\s*=\s*(\d+)\s*;")
    with open(path) as f:
        for line in f:
            m = pat.search(line)
            if m:
                params[m.group(1)] = int(m.group(2))
    for key in ("WORD", "N_LAYERS", "NUM_CLASSES"):
        if key not in params:
            fail(f"{path}: missing localparam {key}")
    if params["WORD"] != WORD:
        fail(f"{path}: WORD = {params['WORD']}, this script expects {WORD}")
    return params


def read_mem(path, expected, max_bits):
    """One hex value per line. Exactly `expected` values, each below 2**max_bits."""
    if not os.path.isfile(path):
        fail(f"cannot find {path}")
    vals = []
    with open(path) as f:
        for lineno, line in enumerate(f, 1):
            s = line.strip()
            if not s:
                continue
            try:
                v = int(s, 16)
            except ValueError:
                fail(f"{path}:{lineno}: not a hex value: {s!r}")
            if v >> max_bits:
                fail(f"{path}:{lineno}: value 0x{v:x} wider than {max_bits} bits")
            vals.append(v)
    if len(vals) != expected:
        fail(f"{path}: {len(vals)} values, expected {expected}")
    return vals


def load_layers(mem_dir, p):
    layers = []
    for i in range(p["N_LAYERS"]):
        n_in, n_out, words = (p.get(f"L{i}_{k}") for k in ("N_IN", "N_OUT", "WORDS"))
        if None in (n_in, n_out, words):
            fail(f"bnn_params.svh: missing L{i}_N_IN / N_OUT / WORDS")
        if words != -(-n_in // WORD):
            fail(f"layer {i}: WORDS = {words} does not match N_IN = {n_in}")
        w = read_mem(os.path.join(mem_dir, f"l{i}_weights.mem"), n_out * words, WORD)

        # Pad check: in each neuron's last word, bits above the real inputs must be 1.
        pad = words * WORD - n_in
        if pad:
            mask = ((1 << pad) - 1) << (WORD - pad)
            for m in range(n_out):
                if w[m * words + words - 1] & mask != mask:
                    fail(f"layer {i} neuron {m}: weight pad bits are not all 1 "
                         f"(wrong file or wrong bit order?)")

        th = None
        if i < p["N_LAYERS"] - 1:
            th = read_mem(os.path.join(mem_dir, f"l{i}_thresh.mem"), n_out, 16)
            if max(th) > n_in + 1:
                fail(f"layer {i}: threshold {max(th)} above N_IN + 1 = {n_in + 1}")
        layers.append(dict(n_in=n_in, n_out=n_out, words=words, w=w, th=th))
    if layers[-1]["n_out"] != p["NUM_CLASSES"]:
        fail(f"last layer has {layers[-1]['n_out']} outputs, NUM_CLASSES = {p['NUM_CLASSES']}")
    return layers


def crc32_words(weights, thresh):
    """CRC-32 over the bytes exactly as they go out on SPI (each value LSB byte first)."""
    data = b"".join(w.to_bytes(8, "little") for w in weights)
    data += b"".join(t.to_bytes(2, "little") for t in thresh)
    return zlib.crc32(data) & 0xFFFFFFFF


def write_header(path, layers, weights, thresh, crc, source):
    offs, toffs, wo, to = [], [], 0, 0
    for L in layers:
        offs.append(wo)
        wo += L["n_out"] * L["words"]
        if L["th"] is not None:
            toffs.append(to)
            to += L["n_out"]
    lines = [
        "/* Generated by tools/mem2c.py. Do not edit; re-run the script instead.",
        f" * Source: {source}",
        " */",
        "#ifndef WEIGHTS_H_INCLUDED",
        "#define WEIGHTS_H_INCLUDED",
        "",
        "#include <stdint.h>",
        "",
        f"#define BNN_N_LAYERS      {len(layers)}",
        f"#define BNN_WEIGHT_WORDS  {len(weights)}u     /* 64-bit words, all layers */",
        f"#define BNN_THRESH_COUNT  {len(thresh)}u      /* 16-bit thresholds, hidden layers */",
        f"#define BNN_WEIGHT_BYTES  ({len(weights)}u * 8u)",
        f"#define BNN_THRESH_BYTES  ({len(thresh)}u * 2u)",
        "",
        "/* CRC-32 (zlib polynomial) over the weight bytes then the threshold bytes,",
        " * each value sent LSB byte first: the exact LOAD_WEIGHTS + LOAD_THRESH payload. */",
        f"#define BNN_PAYLOAD_CRC32 0x{crc:08X}u",
        "",
        "/* Start word of each layer in bnn_weights[] (matches BNN/README.md). */",
    ]
    for i, o in enumerate(offs):
        lines.append(f"#define BNN_L{i}_WORD_START {o}u")
    lines.append("")
    lines.append("/* Start index of each hidden layer in bnn_thresh[]. */")
    for i, o in enumerate(toffs):
        lines.append(f"#define BNN_L{i}_THRESH_START {o}u")
    lines += [
        "",
        "extern const uint64_t bnn_weights[BNN_WEIGHT_WORDS];",
        "extern const uint16_t bnn_thresh[BNN_THRESH_COUNT];",
        "",
        "#endif",
        "",
    ]
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(lines))


def write_source(path, weights, thresh, source):
    out = [
        "/* Generated by tools/mem2c.py. Do not edit; re-run the script instead.",
        f" * Source: {source}",
        " * const data: the linker places these arrays in flash, not RAM. */",
        '#include "weights.h"',
        "",
        "const uint64_t bnn_weights[BNN_WEIGHT_WORDS] = {",
    ]
    for k in range(0, len(weights), 4):
        out.append("    " + " ".join(f"0x{w:016x}ULL," for w in weights[k:k + 4]))
    out += ["};", "", "const uint16_t bnn_thresh[BNN_THRESH_COUNT] = {"]
    for k in range(0, len(thresh), 12):
        out.append("    " + " ".join(f"{t:4d}," for t in thresh[k:k + 12]))
    out += ["};", ""]
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(out))


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    mcu = os.path.dirname(here)
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--mem-dir", default=os.path.join(mcu, "..", "BNN", "mem"))
    ap.add_argument("--out-dir", default=os.path.join(mcu, "src"))
    a = ap.parse_args()

    mem_dir = os.path.normpath(a.mem_dir)
    params_path = os.path.join(mem_dir, "bnn_params.svh")
    params = read_params(params_path)
    layers = load_layers(mem_dir, params)

    weights = [w for L in layers for w in L["w"]]
    thresh = [t for L in layers if L["th"] is not None for t in L["th"]]
    crc = crc32_words(weights, thresh)

    with open(params_path) as f:
        m = re.search(r"from\s+(\S+?)\.?\s", f.readline() + " ")
    model = m.group(1) if m else "unknown checkpoint"
    with open(params_path, "rb") as f:
        svh_hash = hashlib.sha256(f.read()).hexdigest()[:12]
    source = f"{model}, via {mem_dir} (bnn_params.svh sha256 {svh_hash})"

    os.makedirs(a.out_dir, exist_ok=True)
    write_header(os.path.join(a.out_dir, "weights.h"), layers, weights, thresh, crc, source)
    write_source(os.path.join(a.out_dir, "weights.c"), weights, thresh, source)

    print(f"mem2c: read {mem_dir}")
    for i, L in enumerate(layers):
        print(f"  layer {i}: {L['n_in']:>4} -> {L['n_out']:>3}, {L['n_out'] * L['words']:>5} words"
              + (f", {L['n_out']} thresholds" if L["th"] is not None else ""))
    nbytes = len(weights) * 8 + len(thresh) * 2
    print(f"  {len(weights)} weight words + {len(thresh)} thresholds = {nbytes:,} bytes of flash, "
          f"CRC-32 0x{crc:08X}")
    print(f"mem2c: wrote {a.out_dir}/weights.h and weights.c")


if __name__ == "__main__":
    main()